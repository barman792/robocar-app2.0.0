#!/usr/bin/env python3
"""Builds the control page from the sources in this folder.
   Output:  ui_source/out/index.html   and   ui_source/out/web_ui.h  (gzip copy for the ESP32 firmware, optional)
   It also refreshes  ../app/src/main/assets/index.html  (the page that is inside the APK).
   usage:   python3 ui_source/build.py
"""
import os, gzip, shutil
d = os.path.dirname(os.path.abspath(__file__))
rd = lambda f: open(os.path.join(d, f), encoding='utf-8').read()
core = rd('logo_core.svgfrag'); defs = rd('defs.svgfrag')
defs_svg = '<svg width="0" height="0" style="position:absolute" aria-hidden="true">' + defs + '</svg>'
mark_svg = '<svg class="mark" viewBox="14 14 80 72" aria-hidden="true">' + core + '</svg>'
body = rd('body.html').replace('{{DEFS}}', defs_svg).replace('{{MARK}}', mark_svg)
js = "\n".join(rd(f) for f in ['app1.js', 'app2.js', 'app3.js', 'app4.js'])
html = ('<!doctype html>\n<html lang="fa" dir="rtl"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">'
        '<meta name="theme-color" content="#080c12"><title>RoboCar</title>\n<style>\n' + rd('style.css') + '\n</style></head><body>\n' + body +
        '\n<script>\n' + js + '\n</script></body></html>\n')
raw = html.encode('utf-8')
out = os.path.join(d, 'out'); os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'index.html'), 'wb').write(raw)
gz = gzip.compress(raw, 9, mtime=0)
rows = ['  ' + ','.join('0x%02x' % b for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
open(os.path.join(out, 'web_ui.h'), 'w').write(
    '// Generated by ui_source/build.py - do not edit.  index.html (%d bytes) gzip-compressed to %d bytes.\n#pragma once\n#include <Arduino.h>\n'
    'static const size_t WEB_UI_GZ_LEN = %d;\nstatic const uint8_t WEB_UI_GZ[] PROGMEM = {\n%s\n};\n' % (len(raw), len(gz), len(gz), ',\n'.join(rows)))
assets = os.path.join(os.path.dirname(d), 'app', 'src', 'main', 'assets')
if os.path.isdir(assets):
    shutil.copyfile(os.path.join(out, 'index.html'), os.path.join(assets, 'index.html'))
    print('updated', os.path.join(assets, 'index.html'))
print('index.html %d bytes, gzip %d bytes' % (len(raw), len(gz)))
